"""vo_timeline.py <ad>: lay the ad's voice lines on a 30 s clock and write src/vo_<ad>.js + vo/<ad>/timeline.json.
Each line starts after the previous one plus a gap (GAPS); subtitles hold max(1.8 s, speech + 0.6 s), asserted here.
The last line must end by 26 s so the end card holds at least 4 s."""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); A = sys.argv[1]
L = json.load(open(f'{ROOT}/vo/{A}/lines.json')); D = json.load(open(f'{ROOT}/vo/{A}/dur.json'))
LEAD = {'a1': .5, 'a2': .5, 'a3': .5, 'a4': .5, 'a5': .5}[A]
GAPS = {   # gap after each line (s): where the picture needs time to show something
  'a1': [.6, .7, 1.1, .7, .9, 1.4, 1.0, 0],
  'a2': [.4, .9, 1.0, .5, 1.5, .8, .6, 0],
  'a3': [.8, .8, .6, 1.2, .4, .9, .9, 0],
  'a4': [1.1, .3, 1.3, .3, 1.3, .3, 1.6, 0],
  'a5': [.6, .7, .6, 1.0, .6, 1.0, 0],
}[A]
t = LEAD; out = []
for i, l in enumerate(L):
    d = D[l['id']]; out.append({'id': l['id'], 't0': round(t, 3), 't1': round(t + d, 3), 'sub': l['sub']}); t += max(d + GAPS[i], 1.92, d + .72) if i + 1 < len(L) else d
for i, o in enumerate(out):   # subtitle hold: until the next line starts (minus 0.12 s) or the end card
    nxt = out[i + 1]['t0'] - .12 if i + 1 < len(out) else 30.0
    o['hold'] = round(nxt, 3)
    assert nxt - o['t0'] >= max(1.8, o['t1'] - o['t0'] + .6) - 1e-6, f"{A} {o['id']}: subtitle held {nxt - o['t0']:.2f}s"
END = round(out[-1]['t0'] - .1, 3) if A == 'a5' else 25.6   # a5's last line is the call to action itself
assert out[-1]['t1'] <= 26.3 and 30 - END >= 4, f"{A}: last line ends at {out[-1]['t1']}"
open(f'{ROOT}/src/vo_{A}.js', 'w').write(f'// generated by audio/vo_timeline.py\nexport const END = {END};\nexport const VO = {json.dumps(out, ensure_ascii=False, indent=1)};\n')
json.dump({'dur': 30.0, 'end': END, 'lines': out}, open(f'{ROOT}/vo/{A}/timeline.json', 'w'), ensure_ascii=False, indent=1)
print(A, 'end card', END, ' '.join(f"{o['id']}:{o['t0']}-{o['t1']}" for o in out))
