"""Lay the voice-over lines on the film's fixed 30 s clock and write src/vo.js (start/end of each line and its subtitle).
Run from anywhere: python3 audio/vo_timeline.py. Reads vo/lines.json and vo/dur.json (written by core/tts/tts.py).
The starts are set by the beat sheet in TREATMENT.md, not packed end to end: each line lands on the action it names."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = json.load(open(os.path.join(ROOT, 'vo/lines.json'))); D = json.load(open(os.path.join(ROOT, 'vo/dur.json')))
START = {'v01': .5, 'v02': 4.3, 'v03': 6.45, 'v04': 8.3, 'v05': 13.2, 'v06': 16.55, 'v07': 23.35}
DUR = 30.0
out = []
for l in L:
    t0 = START[l['id']]; t1 = round(t0 + D[l['id']], 3)
    if out: assert t0 >= out[-1]['t1'] + .2, f"{l['id']} starts before the previous line ends"
    out.append({'id': l['id'], 't0': t0, 't1': t1, 'en': l.get('sub', l['text'])})
assert out[-1]['t1'] < DUR - 2.5
js = '// Voice-over lines on the film clock (generated by audio/vo_timeline.py from vo/). t0/t1 = speech start/end.\n'
js += f'export const DUR = {DUR};\nexport const VO = ' + json.dumps(out, indent=1) + ';\n'
open(os.path.join(ROOT, 'src/vo.js'), 'w').write(js)
json.dump({'dur': DUR, 'lines': out}, open(os.path.join(ROOT, 'vo/timeline.json'), 'w'), indent=1)
for o in out: print(o['id'], o['t0'], o['t1'], o['en'])
